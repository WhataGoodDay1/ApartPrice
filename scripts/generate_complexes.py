def build_new_entries(items, gu, prefix):
    entries = []
    for i, (name, households, dong) in enumerate(items, start=1):
        variant = name.replace(" ", "")
        entries.append({
            "id": f"{prefix}-{i:03d}",
            "name": name,
            "name_variants": [variant],
            "region": f"대전 {gu} {dong}",
            "lawd_cd": LAWD[gu],
            "households": households,
        })
    return entries


def main():
    with open(CONFIG_PATH, encoding="utf-8") as f:
        cfg = json.load(f)

    existing = cfg["complexes"]
    existing_ids = {c["id"] for c in existing}

    # 나무위키 목록과 겹치는 기존 단지는 households를 이번에 확인된 값으로 보강한다.
    households_backfill = {"yemiji": 998, "cantabile": 1132}
    for c in existing:
        if c["id"] in households_backfill and not c.get("households"):
            c["households"] = households_backfill[c["id"]]

    new_entries = build_new_entries(SEOGU, "서구", "seo") + build_new_entries(YUSEONGGU, "유성구", "yuseong")

    dupes = [e for e in new_entries if e["id"] in existing_ids]
    if dupes:
        raise SystemExit(f"id 충돌: {[e['id'] for e in dupes]}")

    cfg["complexes"] = existing + new_entries
    cfg["_note"] = (
        "lawd_cd는 국토부 API 실호출로 확인 완료(유성구=30200, 서구=30170). name_variants는 "
        "국토부 실거래가 응답의 '아파트' 필드가 등기상 정식 명칭과 다르게 표기되는 경우가 있어 "
        "매칭용으로 둔다. 2026-08-31: 서구/유성구 500세대 이상 단지 전체(나무위키 '공동주택/목록' "
        "기준, MOLIT_API_KEY 없어 실API 미검증)를 일괄 추가함(id 접두사 seo-/yuseong-). "
        "name_variants가 나무위키 표기를 그대로 써서 실제 국토부 등록명과 다를 수 있음 — "
        "collector 최초 실행 후 반드시 data/trades.csv의 raw_apt_name을 훑어보고 "
        "(a) 전혀 매칭 안 된 단지, (b) 이름이 겹쳐 다른 단지 거래가 잘못 들어온 케이스"
        "(예: 예전 크로바아파트 사례)를 점검할 것."
    )

    with open(CONFIG_PATH, "w", encoding="utf-8") as f:
        json.dump(cfg, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print(f"기존 {len(existing)}개 + 신규 {len(new_entries)}개 = 총 {len(cfg['complexes'])}개")


if __name__ == "__main__":
    main()
